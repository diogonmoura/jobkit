// Embed postgres/schema.sql + postgres/migrations/*.sql in src/db/postgres-sql.generated.ts, because the Worker has no filesystem.
// The baseline comes first with id 0000_schema.sql; migrations follow in file-name order.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "postgres", "migrations");
const read = (p) => fs.readFileSync(p, "utf8").trim() + "\n";

const migrations = [
  { id: "0000_schema.sql", sql: read(path.join(root, "postgres", "schema.sql")) },
  ...fs
    .readdirSync(dir)
    .filter((f) => f.endsWith(".sql"))
    .sort()
    .map((f) => ({ id: f, sql: read(path.join(dir, f)) })),
];

const out = [
  "// Generated by scripts/build-postgres-sql.mjs from postgres/schema.sql and postgres/migrations. Do not edit.",
  "export const POSTGRES_MIGRATIONS: { id: string; sql: string }[] = " + JSON.stringify(migrations, null, 2) + ";",
  "",
].join("\n");
const target = path.join(root, "src", "db", "postgres-sql.generated.ts");
fs.writeFileSync(target, out);
console.log("wrote", path.relative(root, target), migrations.length, "migration(s)");
