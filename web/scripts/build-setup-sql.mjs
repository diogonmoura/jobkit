// Concatenate supabase/schema.sql + migrations into one idempotent file the setup wizard offers for the SQL editor.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const dir = path.join(root, "supabase", "migrations");
const parts = [path.join(root, "supabase", "schema.sql"), ...fs.readdirSync(dir).filter((f) => f.endsWith(".sql")).sort().map((f) => path.join(dir, f))];

// "alter publication ... add table" fails when the table is already published (or the publication is missing): guard it.
const guard = (sql) =>
  sql.replace(/^alter publication supabase_realtime add table ([\w.]+);$/gim, (_m, t) => {
    const [schema, table] = t.includes(".") ? t.split(".") : ["public", t];
    return `do $$ begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
     and not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = '${schema}' and tablename = '${table}') then
    alter publication supabase_realtime add table ${schema}.${table};
  end if;
end $$;`;
  });

// "create policy" and "add constraint" have no IF NOT EXISTS: drop first so a re-run works.
const rerunnable = (sql) =>
  sql
    .replace(/^create policy ("[^"]+"|\w+)\s+on\s+([\w.]+)/gim, (m, name, table) => `drop policy if exists ${name} on ${table};\n${m}`)
    .replace(/^alter table ([\w.]+) add constraint (\w+)/gim, (m, table, name) => `alter table ${table} drop constraint if exists ${name};\n${m}`);

const out = [
  "-- jobkit: complete database setup (generated by scripts/build-setup-sql.mjs; safe to run more than once).",
  "-- Paste into Supabase Dashboard -> SQL Editor -> New query, then Run.",
  "",
  ...parts.map((p) => `-- ===== ${path.relative(root, p)} =====\n${rerunnable(guard(fs.readFileSync(p, "utf8"))).trim()}\n`),
].join("\n");
const target = path.join(root, "public", "setup", "jobkit-schema.sql");
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out + "\n-- Tell the Data API (PostgREST) about the new tables.\nnotify pgrst, 'reload schema';\n");
console.log("wrote", path.relative(root, target), out.length, "bytes");
